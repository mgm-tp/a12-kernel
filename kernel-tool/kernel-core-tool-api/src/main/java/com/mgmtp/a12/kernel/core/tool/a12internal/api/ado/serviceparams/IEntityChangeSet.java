package com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.serviceparams;

/**
 * The interface is used to specify a change to one entity.
 * It can be used in {@link IModelChanges}
 * <ul>
 * <li>rules specify a restriction of max values of entities.</li>
 * </ul>
 */

public interface IEntityChangeSet {

	/**
	 * @return the full name of the entity.
	 */
	public String getFullName();

	/**
	 * @return the new max values of the entity.
	 */
	public long[] getNewMaxValue();
}
