package com.mgmtp.a12.kernel.core.service.internal.extservices;

import java.util.Locale;

import org.apache.commons.lang3.StringUtils;

import com.mgmtp.a12.kernel.core.parser.internal.check.util.EntityUtils;
import com.mgmtp.a12.kernel.core.parser.internal.grammar.languages.ConditionMultiLanguageHandler;
import com.mgmtp.a12.kernel.core.parser.internal.parsebaum.util.FeldIdUtil;
import com.mgmtp.a12.kernel.core.service.internal.serviceparams.LanguageSpecificPropertiesLookup;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IField;

/**
 * Implementation of a rule representing a mandatory field test.
 * <p>
 * Rules of this type are created by {@link AutogeneratedRulesService}.
 */
class MandatoryFieldRuleImpl extends MandatoryRuleImpl {

	private static final String RULE_CONDITION_ABSOLUTE = "mandatoryFieldNonRepRuleCondition";
	private static final String RULE_CONDITION_KEY = "mandatoryFieldRuleCondition";
	private static final String RULE_CONDITION_ROW_ITERATION_KEY = "mandatoryFieldRowIterationRuleCondition";
	private static final String RULE_CONDITION_IN_VORDRUCK_KEY = "mandatoryFieldInVordruckRuleCondition";

	private static final String RULE_ERROR_CODE = "mandatoryField";

	/**
	 * @param relativeTo
	 * 		group path which the requiredness of the field depends on. If the field is absolutely required, this should be null.
	 */
	public MandatoryFieldRuleImpl(IField mandatoryField, String relativeTo, boolean isHModel, Locale languageUsedInConditionText,
			ConditionMultiLanguageHandler mlh) {
		super(mandatoryField, relativeTo, isHModel, languageUsedInConditionText, mlh);
	}

	protected String createErrorConditionText(String fieldParentPath, boolean isHModel) {
		String shortNameInConditionText = FeldIdUtil.quoteNameIfNecessary(errorEntityName, mlh);
		if (isHModel && EntityUtils.isRootGroup(fieldParentPath)) {
			String ruleConditionTemplate = new LanguageSpecificPropertiesLookup(locale).getProperty(RULE_CONDITION_IN_VORDRUCK_KEY);
			return String.format(ruleConditionTemplate, EntityUtils.getRootGroupName(fieldParentPath), shortNameInConditionText);
		}
		if (isHModel && EntityUtils.getMaxZeile(errorEntity) > 1) {
			String ruleConditionTemplate = new LanguageSpecificPropertiesLookup(locale).getProperty(
					RULE_CONDITION_ROW_ITERATION_KEY);
			return String.format(ruleConditionTemplate, shortNameInConditionText);
		}
		if (StringUtils.isEmpty(relativeTo)) {
			String ruleConditionTemplate = new LanguageSpecificPropertiesLookup(locale).getProperty(RULE_CONDITION_ABSOLUTE);
			return String.format(ruleConditionTemplate, shortNameInConditionText);
		}
		String relativeToInConditionText = FeldIdUtil.quoteNameIfNecessary(relativeTo, mlh);
		String ruleConditionTemplate = new LanguageSpecificPropertiesLookup(locale).getProperty(RULE_CONDITION_KEY);
		return String.format(ruleConditionTemplate, relativeToInConditionText, shortNameInConditionText);
	}

	@Override
	public String getErrorCode() {
		return RULE_ERROR_CODE;
	}

	@Override
	public GenerationType getGenerationType() {
		return GenerationType.MANDATORY_FIELD;
	}
}