package com.mgmtp.a12.kernel.core.service.internal.extservices;

import java.util.Collections;
import java.util.Locale;
import java.util.Map;

import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IRule;

/**
 * The interface <code>IAutogeneratedRule</code> specifies a rule that is generated automatically
 * during code generation from other properties.
 * <p>
 * It is usually tested before other rules and generates formal errors instead of rule errors.
 * <p>
 * If the error messages were generated in the code generator instead of the runtime, the generation
 * of code for an additional language needs changes in the corresponding generator because the error
 * message for the new language needs to be specified. If, on the other hand the error messages are
 * treated as formal error messages, the languages are specified in the runtime and can be added by
 * adding a new properties file for formal errors.
 */
public interface IAutogeneratedRule extends IRule {
	public static final String RULE_NAME_PREFIX = "vk_vk";

	public enum GenerationType {
		MANDATORY_FIELD,
		UNIQUE_FIELD,
		UNIQUE_VALUE,
		SOLITARY_FIELD
	}

	/**
	 * Get the intention behind the generation of the rule. E.g. generation for mandatory fields
	 * ({@link GenerationType#MANDATORY_FIELD}).
	 */
	public GenerationType getGenerationType();

	/**
	 * Returns <code>null</code> because for this type of rule, formal error messages are generated.
	 *
	 * @see com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IRule#getErrorMessage(java.util.Locale)
	 */
	@Override
	default String getErrorMessage(Locale loc) {
		return null;
	}

	/**
	 * Returns an empty map because for this type of rule, formal error messages are generated.
	 *
	 * @see com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IRule#getErrorMessage(java.util.Locale)
	 */
	@Override
	default Map<Locale, String> getErrorMessages() {
		return Collections.emptyMap();
	}
}
