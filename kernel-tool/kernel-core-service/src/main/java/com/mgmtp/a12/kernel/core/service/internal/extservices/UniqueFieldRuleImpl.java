package com.mgmtp.a12.kernel.core.service.internal.extservices;

import java.util.List;
import java.util.Locale;

import com.mgmtp.a12.kernel.core.parser.internal.check.util.EntityUtils;
import com.mgmtp.a12.kernel.core.parser.internal.grammar.languages.ConditionMultiLanguageHandler;
import com.mgmtp.a12.kernel.core.parser.internal.parsebaum.util.FeldIdUtil;
import com.mgmtp.a12.kernel.core.service.internal.serviceparams.LanguageSpecificPropertiesLookup;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IEntity;
import com.mgmtp.a12.kernel.core.tool.a12internal.api.ado.IField;

/**
 * Implementation of a rule representing the unique constraint for an index field.
 * <p>
 * Rules of this type are created by {@link AutogeneratedRulesService}.
 */
class UniqueFieldRuleImpl implements IAutogeneratedRule {

	private static final String RULE_NAME_SUFFIX = "_unq";
	private static final String GROUP_SEPARATOR = "_vk_grp_";

	private static final String RULE_CONDITION_KEY = "uniqueFieldRuleCondition";

	private static final String RULE_ERROR_CODE = "uniqueField";

	private final IField errorField;
	private final String ruleName;
	private final String errorConditionText;
	private final Locale locale;
	private final GenerationType generationType;
	private final ConditionMultiLanguageHandler mlh;

	public UniqueFieldRuleImpl(IField uniqueField, GenerationType generationType, Locale languageUsedInConditionText,
			ConditionMultiLanguageHandler mlh) {
		this.errorField = uniqueField;
		this.mlh = mlh;
		String fieldShortName = EntityUtils.getShortName(errorField.getFullName());

		String fieldParentPath = EntityUtils.getParentPath(uniqueField.getFullName());
		String ruleParentPath;
		String relativeFieldName;
		String groupName;
		if (EntityUtils.isRootGroup(fieldParentPath)) {
			// For root group fields, the rule resides in the root group, too.
			ruleParentPath = fieldParentPath;
			relativeFieldName = fieldShortName;
			groupName = GROUP_SEPARATOR + EntityUtils.getShortName(ruleParentPath);
		} else {
			// else one level above
			ruleParentPath = EntityUtils.getParentPath(fieldParentPath);
			relativeFieldName = EntityUtils.createPath(EntityUtils.getShortName(fieldParentPath), fieldShortName);
			groupName = EntityUtils.getShortName(fieldParentPath);
		}
		String ruleShortName = RULE_NAME_PREFIX + groupName + GROUP_SEPARATOR + fieldShortName + RULE_NAME_SUFFIX;
		this.ruleName = EntityUtils.createPath(ruleParentPath, ruleShortName);
		this.locale = languageUsedInConditionText;
		this.errorConditionText = createErrorConditionText(relativeFieldName);
		this.generationType = generationType;
	}

	private String createErrorConditionText(String relativeFieldName) {
		String ruleConditionTemplate = new LanguageSpecificPropertiesLookup(locale).getProperty(RULE_CONDITION_KEY);
		return String.format(ruleConditionTemplate, FeldIdUtil.quoteNameIfNecessary(relativeFieldName, mlh));
	}

	@Override
	public String getFullName() {
		return ruleName;
	}

	@Override
	public String getErrorConditionText() {
		return errorConditionText;
	}

	@Override
	public IEntity getErrorEntity() {
		return errorField;
	}

	@Override
	public String getErrorCode() {
		return RULE_ERROR_CODE;
	}

	@Override
	public RuleSeverityType getSeverityType() {
		return RuleSeverityType.ERROR;
	}

	@Override
	public GenerationType getGenerationType() {
		return generationType;
	}

	@Override public List<String> getCustomRefErrorEntitiesIfFilled() {
		return List.of(); // the UniqueField Rules are not manually modeled and don't have customRefErrorEntities
	}

	@Override public List<String> getCustomRefErrorEntitiesIfNotFilled() {
		return List.of(); // the UniqueField Rules are not manually modeled and don't have customRefErrorEntities
	}

}